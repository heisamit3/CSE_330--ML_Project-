xai_load_cell = {
    "cell_type": "code",
    "execution_count": None,
    "metadata": {},
    "outputs": [],
    "source": [
        "# ============================================================\n",
        "# EXPLAINABLE AI - EXPLAINER LLM LOADER\n",
        "# ============================================================\n",
        "\n",
        "def load_explainer():\n",
        "    \"\"\"\n",
        "    Load the best available LLM for generating explanations.\n",
        "    Priority: Qwen 2.5 7B (4-bit GPU) > FLAN-T5 Large (CPU/GPU)\n",
        "    \"\"\"\n",
        "    if not USE_LLM_EXPLAINER:\n",
        "        return None, None, None\n",
        "\n",
        "    from transformers import AutoModelForCausalLM, AutoModelForSeq2SeqLM\n",
        "\n",
        "    # Try GPU 4-bit Qwen first\n",
        "    if device == \"cuda\":\n",
        "        try:\n",
        "            from transformers import BitsAndBytesConfig\n",
        "            bnb_cfg = BitsAndBytesConfig(\n",
        "                load_in_4bit=True,\n",
        "                bnb_4bit_use_double_quant=True,\n",
        "                bnb_4bit_quant_type=\"nf4\",\n",
        "                bnb_4bit_compute_dtype=torch.float16,\n",
        "            )\n",
        "            tok = AutoTokenizer.from_pretrained(EXPLAINER_MODEL, use_fast=True)\n",
        "            mdl = AutoModelForCausalLM.from_pretrained(\n",
        "                EXPLAINER_MODEL,\n",
        "                quantization_config=bnb_cfg,\n",
        "                device_map=\"auto\",\n",
        "                torch_dtype=torch.float16,\n",
        "            )\n",
        "            mdl.eval()\n",
        "            log(f\"Loaded explainer (4-bit GPU): {EXPLAINER_MODEL}\")\n",
        "            return \"causal\", mdl, tok\n",
        "        except Exception as e:\n",
        "            log(f\"4-bit explainer failed: {str(e)[:100]}\")\n",
        "\n",
        "    # Fallback: FLAN-T5\n",
        "    tok = AutoTokenizer.from_pretrained(EXPLAINER_FALLBACK_MODEL, use_fast=True)\n",
        "    mdl = AutoModelForSeq2SeqLM.from_pretrained(EXPLAINER_FALLBACK_MODEL).to(device)\n",
        "    mdl.eval()\n",
        "    log(f\"Loaded explainer (fallback): {EXPLAINER_FALLBACK_MODEL}\")\n",
        "    return \"seq2seq\", mdl, tok\n",
        "\n",
        "\n",
        "def llm_generate(prompt: str, max_new_tokens=320, explainer_kind=None, explainer_mdl=None, explainer_tok=None):\n",
        "    \"\"\"Generate text from the loaded LLM.\"\"\"\n",
        "    if explainer_mdl is None:\n",
        "        return \"\"\n",
        "    if explainer_kind == \"causal\":\n",
        "        inputs = explainer_tok(prompt, return_tensors=\"pt\", truncation=True, max_length=2048).to(explainer_mdl.device)\n",
        "        with torch.no_grad():\n",
        "            out = explainer_mdl.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False, num_beams=1)\n",
        "        text = explainer_tok.decode(out[0], skip_special_tokens=True)\n",
        "        return text[len(prompt):].strip() if text.startswith(prompt) else text.strip()\n",
        "    else:\n",
        "        inputs = explainer_tok(prompt, return_tensors=\"pt\", truncation=True, max_length=1024).to(device)\n",
        "        with torch.no_grad():\n",
        "            out = explainer_mdl.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False, num_beams=4)\n",
        "        return explainer_tok.decode(out[0], skip_special_tokens=True).strip()\n",
        "\n",
        "\n",
        "# Load the explainer model\n",
        "log(\"Loading explainer LLM...\")\n",
        "EXPLAINER_KIND, explainer_model, explainer_tok = load_explainer()"
    ]
}

xai_kb_cell = {
    "cell_type": "code",
    "execution_count": None,
    "metadata": {},
    "outputs": [],
    "source": [
        "# ============================================================\n",
        "# EXPLAINABLE AI - MISCONCEPTION KNOWLEDGE BASE\n",
        "# ============================================================\n",
        "\n",
        "def build_misconception_kb(train_df, le):\n",
        "    \"\"\"\n",
        "    Build a Misconception Knowledge Base using the explainer LLM.\n",
        "    Each misconception gets a 'card' with:\n",
        "    - plain_definition: Simple explanation\n",
        "    - why_common: Why students make this mistake\n",
        "    - fix_steps: How to correct the thinking\n",
        "    \"\"\"\n",
        "    global kb\n",
        "    \n",
        "    # Extract misconceptions from labels\n",
        "    train_df[\"miscon_only\"] = train_df[\"target\"].apply(\n",
        "        lambda x: x.split(\":\")[1] if \":\" in str(x) else str(x)\n",
        "    )\n",
        "    freq = Counter(train_df[\"miscon_only\"].tolist())\n",
        "    top_miscons = [m for m, _ in freq.most_common(KB_BUILD_TOP_N) if m != \"NA\"]\n",
        "    log(f\"\\nBuilding KB for {len(top_miscons)} misconception types...\")\n",
        "\n",
        "    # Check for cached KB\n",
        "    if KB_PATH.exists():\n",
        "        kb = json.loads(KB_PATH.read_text(encoding=\"utf-8\"))\n",
        "        log(f\"Loaded cached KB: {len(kb)} entries\")\n",
        "        return kb\n",
        "\n",
        "    kb = {}\n",
        "    for i, miscon in enumerate(top_miscons, start=1):\n",
        "        sub = train_df[train_df[\"miscon_only\"] == miscon]\n",
        "        sample = sub.sample(n=min(KB_EXAMPLES_PER_MISCON, len(sub)), random_state=42)\n",
        "\n",
        "        examples = []\n",
        "        for _, r in sample.iterrows():\n",
        "            examples.append({\n",
        "                \"question\": str(r[\"QuestionText\"])[:200],\n",
        "                \"student_answer\": str(r[\"MC_Answer\"]),\n",
        "                \"student_expl\": str(r[\"StudentExplanation\"])[:200],\n",
        "            })\n",
        "\n",
        "        prompt = f\"\"\"You are a math teacher writing a misconception knowledge card.\n",
        "\n",
        "Misconception name: {miscon}\n",
        "\n",
        "Student examples:\n",
        "{json.dumps(examples, ensure_ascii=False, indent=2)}\n",
        "\n",
        "Return ONLY valid JSON (no markdown) with keys:\n",
        "- \"plain_definition\": 1-2 sentence definition in simple words\n",
        "- \"why_common\": Why students make this mistake (1-2 sentences)\n",
        "- \"fix_steps\": List of 3-4 short steps to fix the thinking\n",
        "\"\"\"\n",
        "        try:\n",
        "            out = llm_generate(prompt, 420, EXPLAINER_KIND, explainer_model, explainer_tok)\n",
        "            # Extract JSON from response\n",
        "            match = re.search(r'\\{[\\s\\S]*\\}', out)\n",
        "            if match:\n",
        "                kb[miscon] = json.loads(match.group())\n",
        "            else:\n",
        "                kb[miscon] = {\"plain_definition\": out[:300], \"why_common\": \"\", \"fix_steps\": []}\n",
        "        except Exception as e:\n",
        "            kb[miscon] = {\"plain_definition\": f\"Error: {str(e)[:100]}\", \"why_common\": \"\", \"fix_steps\": []}\n",
        "\n",
        "        if i % 10 == 0:\n",
        "            log(f\"  Built {i}/{len(top_miscons)} KB cards...\")\n",
        "\n",
        "    # Save KB\n",
        "    KB_PATH.write_text(json.dumps(kb, ensure_ascii=False, indent=2), encoding=\"utf-8\")\n",
        "    log(f\"Saved KB to {KB_PATH}\")\n",
        "    return kb\n",
        "\n",
        "\n",
        "# Build the knowledge base\n",
        "kb = build_misconception_kb(train, le)\n",
        "log(f\"\\nKB Sample (first entry):\")\n",
        "if kb:\n",
        "    first_key = list(kb.keys())[0]\n",
        "    log(f\"  {first_key}: {json.dumps(kb[first_key], indent=2)[:500]}\")"
    ]
}

xai_feedback_cell = {
    "cell_type": "code",
    "execution_count": None,
    "metadata": {},
    "outputs": [],
    "source": [
        "# ============================================================\n",
        "# EXPLAINABLE AI - TEACHER FEEDBACK GENERATOR\n",
        "# ============================================================\n",
        "\n",
        "def rule_based_verify(feedback: str, is_correct: int, correct_choice: str) -> str:\n",
        "    \"\"\"\n",
        "    Rule-based post-hoc check:\n",
        "    - If student is correct, soften negative language\n",
        "    - If student is incorrect and we know the answer, prepend it\n",
        "    \"\"\"\n",
        "    txt = feedback.strip()\n",
        "    if is_correct == 1:\n",
        "        txt = re.sub(r\"\\bincorrect\\b\", \"not quite right\", txt, flags=re.I)\n",
        "        txt = re.sub(r\"\\bwrong\\b\", \"not quite right\", txt, flags=re.I)\n",
        "    if is_correct == 0 and correct_choice and correct_choice not in txt:\n",
        "        txt = f\"Correct answer: {correct_choice}\\n\\n\" + txt\n",
        "    return txt\n",
        "\n",
        "\n",
        "def llm_verify(feedback: str) -> str:\n",
        "    \"\"\"Optional LLM-based verification to fix contradictions.\"\"\"\n",
        "    if not USE_LLM_VERIFIER or explainer_model is None:\n",
        "        return feedback\n",
        "    prompt = f\"Fix contradictions and make this concise (8-14 lines), student-friendly:\\n\\n{feedback}\"\n",
        "    out = llm_generate(prompt, 260, EXPLAINER_KIND, explainer_model, explainer_tok)\n",
        "    return out if out else feedback\n",
        "\n",
        "\n",
        "def generate_teacher_feedback(row, pred_label: str, pred_top3: list, correct_lookup: dict) -> str:\n",
        "    \"\"\"\n",
        "    Generate an explanation for the predicted misconception.\n",
        "    Combines: DeepSeek prediction + Knowledge Base card + LLM generation.\n",
        "    \"\"\"\n",
        "    qtext = str(row[\"QuestionText\"])\n",
        "    ans = str(row[\"MC_Answer\"])\n",
        "    expl = str(row[\"StudentExplanation\"])\n",
        "    qid = row[\"QuestionId\"]\n",
        "    correct_ans = correct_lookup.get(qid, \"\")\n",
        "    ic = int(row.get(\"is_correct\", -1))\n",
        "    ic_str = {1: \"Yes\", 0: \"No\"}.get(ic, \"Unknown\")\n",
        "\n",
        "    miscon = pred_label.split(\":\", 1)[1] if \":\" in pred_label else pred_label\n",
        "    card = kb.get(miscon, {})\n",
        "\n",
        "    if USE_LLM_EXPLAINER and explainer_model is not None:\n",
        "        prompt = f\"\"\"You are a kind, clear math teacher. Use ONLY the info below.\n",
        "\n",
        "Question: {qtext[:300]}\n",
        "Student chose: {ans}\n",
        "Is correct? {ic_str}\n",
        "Correct choice: {correct_ans}\n",
        "Student explanation: {expl[:300]}\n",
        "Top predictions: {pred_top3}\n",
        "Misconception knowledge card:\n",
        "{json.dumps(card, ensure_ascii=False, indent=2)[:600]}\n",
        "\n",
        "Write:\n",
        "- 1-2 lines: what the student seems to think\n",
        "- 1 line: misconception in simple words\n",
        "- 4-7 short steps: correct logic\n",
        "- 1 line: self-check question\n",
        "Keep it concise and encouraging.\n",
        "\"\"\"\n",
        "        fb = llm_generate(prompt, 320, EXPLAINER_KIND, explainer_model, explainer_tok) or \"Feedback generation failed.\"\n",
        "    else:\n",
        "        fb = f\"\"\"Teacher Feedback\n",
        "Student chose: {ans} | Correct: {ic_str} | Correct answer: {correct_ans}\n",
        "Predicted misconception: {pred_label}\n",
        "\n",
        "Steps to fix:\n",
        "1) Re-read what the question is asking.\n",
        "2) Write down the correct mathematical rule.\n",
        "3) Apply it step-by-step.\n",
        "4) Check with a simpler example.\n",
        "\n",
        "Self-check: Does your rule still work if the numbers change slightly?\n",
        "\"\"\"\n",
        "\n",
        "    fb = rule_based_verify(fb, ic, correct_ans)\n",
        "    fb = llm_verify(fb)\n",
        "    return fb.strip()\n",
        "\n",
        "\n",
        "log(\"Teacher feedback generator ready!\")"
    ]
}

